"""A chatbot as a DeepTeam YAML config for `deepteam run config.yaml` (CLI / CI).

The zip holds config.yaml (models, target with a callback, system_config,
default_vulnerabilities, attacks, as in DeepTeam's YAML docs), the callback
(model_callback.py + chatbot_client.py + chatbot.json: the same client the CI
export uses, export_suite.CLIENT_PY), .env.example and a README. Secret header
values are never exported: their names are listed, values come from
LLM_EVAL_HEADERS (a JSON object) at run time, as in the CI export.
"""
from __future__ import annotations

import io
import json
import zipfile

import yaml

from backend.export_suite import CLIENT_PY, _client_config

CALLBACK_PY = '''"""DeepTeam model_callback for the chatbot under test (generated by the LLM Judge app)."""
from deepteam.test_case import RTTurn

from chatbot_client import ask


def model_callback(input: str, turns: list[RTTurn] = None) -> RTTurn:
    # Each message is sent on its own; the chatbot's own session keeps earlier turns.
    return RTTurn(role="assistant", content=ask(input))
'''

README = """# DeepTeam red teaming for {name}

Generated by the LLM Judge app. Run DeepTeam's own CLI on this chatbot:

```bash
pip install -U deepteam requests
# secret headers (cookies, keys) of the chatbot, as JSON:
export LLM_EVAL_HEADERS='{{"Authorization": "Bearer ..."}}'
deepteam run config.yaml
```

Put your judge API key in config.yaml (models > api_key), or use a model name
DeepTeam knows (e.g. gpt-4o) with its usual environment variable.
Edit `default_vulnerabilities`, `attacks` and `system_config` in config.yaml.
Secret headers needed: {secrets}.
"""


def build_config(target: dict, judge: dict, opts: dict | None = None) -> dict:
    opts = opts or {}
    config = target.get("config") or {}
    model = {
        "model": {
            "provider": "local",
            "model": judge.get("model", ""),
            "base_url": judge.get("base_url", ""),
            "api_key": "<your judge API key>",
            "temperature": 0,
        }
    }
    vulnerabilities = [
        {"name": v["class"], **({"types": list(v["types"])} if v.get("types") else {})}
        for v in opts.get("vulnerabilities") or []
    ] or [{"name": "Bias"}, {"name": "Toxicity"}, {"name": "PIILeakage"}, {"name": "PromptLeakage"}]
    attacks = [{"name": a} for a in opts.get("attacks") or []] or [
        {"name": "PromptInjection"}, {"name": "Roleplay"}, {"name": "LinearJailbreaking"}]
    return {
        "models": {"simulator": model, "evaluation": model},
        "target": {
            "purpose": opts.get("target_purpose") or config.get("persona") or "",
            "callback": {"file": "model_callback.py", "function": "model_callback"},
        },
        "system_config": {
            "max_concurrent": int(opts.get("max_concurrent") or 5),
            "attacks_per_vulnerability_type": int(opts.get("attacks_per_vulnerability_type") or 1),
            "run_async": True,
            "ignore_errors": True,
            "output_folder": "deepteam-results",
        },
        "default_vulnerabilities": vulnerabilities,
        "attacks": attacks,
    }


def build_zip(target: dict, judge: dict, opts: dict | None = None) -> bytes:
    config = target.get("config") or {}
    client = _client_config(config)
    yaml_text = ("# DeepTeam config generated by the LLM Judge app: deepteam run config.yaml\n"
                 + yaml.safe_dump(build_config(target, judge, opts), sort_keys=False, allow_unicode=True))
    secrets = ", ".join(client["secret_header_names"]) or "none"
    env = ("# Secret headers of the chatbot as JSON, e.g. {\"Cookie\": \"...\"}\n"
           "LLM_EVAL_HEADERS={}\n")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("config.yaml", yaml_text)
        z.writestr("model_callback.py", CALLBACK_PY)
        z.writestr("chatbot_client.py", CLIENT_PY)
        z.writestr("chatbot.json", json.dumps(client, indent=2, ensure_ascii=False))
        z.writestr(".env.example", env)
        z.writestr("README.md", README.format(name=target.get("name", "the chatbot"), secrets=secrets))
    return buf.getvalue()
