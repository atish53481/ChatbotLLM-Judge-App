"""G-Eval metrics run the way DeepEval recommends for production: fixed
evaluation_steps (no steps regenerated by the judge on every run), with the
criteria kept for the dashboard."""
from unittest.mock import MagicMock

import pytest
from deepeval.metrics import GEval
from deepeval.models import DeepEvalBaseLLM

from backend import metrics_catalog as catalog
from tests.test_app import app_module, client  # noqa: F401  (fixtures)


class Offline(DeepEvalBaseLLM):  # never called: only the metric's settings are checked
    def __init__(self):
        super().__init__("offline")

    def load_model(self):
        return None

    def generate(self, prompt, schema=None):
        raise AssertionError("no judge call expected")

    async def a_generate(self, prompt, schema=None):
        raise AssertionError("no judge call expected")

    def get_model_name(self):
        return "offline"


GEVAL_KEYS = {
    "correctness", "helpfulness", "citation_quality", "robustness", "self_check", "no_prompt_leak",
    "prompt_injection", "jailbreak", "encoded_injection", "data_exfiltration", "social_engineering",
    "domain_misuse", "non_advice", "role_violation", "harmful_content", "multi_turn_jailbreak",
}


@pytest.mark.parametrize("key", sorted(GEVAL_KEYS))
def test_every_shipped_geval_has_fixed_evaluation_steps(key):
    spec = catalog.get_spec(key)
    metric = spec.build_metric(Offline())
    assert isinstance(metric, GEval)
    assert len(spec.evaluation_steps) >= 3
    assert metric.evaluation_steps == list(spec.evaluation_steps)
    assert metric.criteria == spec.criteria  # still shown on the dashboard
    # The judge never has to write the steps itself.
    assert metric._generate_evaluation_steps(False) == list(spec.evaluation_steps)


def test_security_steps_carry_each_probes_own_rule():
    spec = catalog.get_spec("harmful_content")
    assert any(spec.criteria in step for step in spec.evaluation_steps)
    assert catalog.get_spec("jailbreak").evaluation_steps != spec.evaluation_steps


def test_only_geval_specs_have_steps():
    with_steps = {s.key for s in catalog.ALL_SPECS if s.evaluation_steps}
    assert with_steps == GEVAL_KEYS


def test_metrics_api_lists_the_steps(client):  # noqa: F811
    rows = {m["key"]: m for m in client.get("/api/metrics").json()}
    assert rows["correctness"]["evaluation_steps"] == list(catalog.get_spec("correctness").evaluation_steps)
    assert rows["answer_relevancy"]["evaluation_steps"] == []


def test_calibration_examples_become_a_step_when_steps_are_fixed():
    from backend.dashboard.runner import _calibrate

    metric = catalog.get_spec("correctness").build_metric(Offline())
    before = list(metric.evaluation_steps)
    examples = [{"question": "q", "actual_output": "a", "human_score": 0.4, "note": ""}]
    assert _calibrate(metric, examples) == 1
    assert metric.evaluation_steps[:-1] == before
    assert "Human score: 0.40" in metric.evaluation_steps[-1]
    # The spec's own steps are untouched for the next run.
    assert list(catalog.get_spec("correctness").evaluation_steps) == before
    assert _calibrate(MagicMock(criteria="c", evaluation_steps=None), examples) == 1


def test_exported_suite_keeps_the_steps():
    from backend.export_suite import _metric_entry

    spec = catalog.get_spec("helpfulness")
    entry, why = _metric_entry(spec, 0.7, {})
    assert why is None and entry["evaluation_steps"] == list(spec.evaluation_steps)
